/**
 * Closure API (Feature 25) — typed wrapper over the existing HTTP client.
 *
 * F11 endpoints, verified against the backend controller and integration tests:
 * - `POST /api/closures` with `{ preparationId, status?, finalNotes? }` (201,
 *   `closedAt` stamped server-side; status defaults to COMPLETED; 404 unknown or
 *   soft-deleted preparation / missing execution; 409 proposal not ACCEPTED,
 *   deposit not reached, execution not COMPLETED, or an active closure already
 *   exists);
 * - `GET /api/closures?preparationId=&status=` (real global list, every filter
 *   optional, soft-deleted rows excluded);
 * - `GET /api/closures/{id}`;
 * - `DELETE /api/closures/{id}` (204, **soft** deletion, releases the 1:1 slot).
 *
 * There is deliberately no update method: an active closure is definitive and
 * `PUT /api/closures/{id}` always answers 409. The UI never offers a form for
 * it.
 */

import { ApiError, api } from "@/lib/api";
import type { ClosureStatus, ServiceClosure } from "@/types/api";

/** Body of `POST /api/closures` (exact F11 contract). */
export interface CreateClosurePayload {
  preparationId: string;
  /** Chosen once at creation; both F11 statuses are allowed. */
  status: ClosureStatus;
  /** Optional, max 2000 characters; `null` when empty. */
  finalNotes: string | null;
}

export interface ClosureFilters {
  preparationId?: string | null;
  status?: ClosureStatus | "";
}

/** List path with only the filters that are actually set. */
export function closuresPath(filters: ClosureFilters = {}): string {
  const params = new URLSearchParams();
  if (filters.preparationId) {
    params.set("preparationId", filters.preparationId);
  }
  if (filters.status) {
    params.set("status", filters.status);
  }
  const query = params.toString();
  return query ? `/api/closures?${query}` : "/api/closures";
}

export const closuresApi = {
  list(filters: ClosureFilters = {}): Promise<ServiceClosure[]> {
    return api.get<ServiceClosure[]>(closuresPath(filters));
  },
  get(id: string): Promise<ServiceClosure> {
    return api.get<ServiceClosure>(`/api/closures/${id}`);
  },
  /** F11 creation payload: no `closedAt`, it is always generated by the server. */
  create(payload: CreateClosurePayload): Promise<ServiceClosure> {
    return api.post<ServiceClosure>("/api/closures", payload);
  },
  /** Soft deletion: the closure leaves the API, the row is kept. */
  remove(id: string): Promise<void> {
    return api.delete(`/api/closures/${id}`);
  },
};

/** Message for a failure while reading a closure or its list. */
export function closureErrorMessage(error: unknown): string {
  if (!(error instanceof ApiError)) {
    return "Une erreur inattendue est survenue. Réessayez.";
  }
  switch (error.status) {
    case 400:
      return "Les informations de la clôture sont invalides.";
    case 401:
      return "Votre session a expiré. Reconnectez-vous puis réessayez.";
    case 403:
      return "Accès refusé.";
    case 404:
      return "Cette clôture n'existe pas ou a été supprimée.";
    case 409:
      return "Cette clôture a été modifiée entre-temps. Rechargez-la avant de réessayer.";
    case 0:
      return error.message;
    default:
      return error.message;
  }
}

/**
 * Message for a failed creation. The backend is the final authority: a 409
 * means the F11 conditions no longer hold or a closure already exists, and the
 * user must reload the preparation instead of retrying blindly.
 */
export function closureCreateErrorMessage(error: unknown): string {
  if (!(error instanceof ApiError)) {
    return "Une erreur inattendue est survenue. Réessayez.";
  }
  switch (error.status) {
    case 400:
      return "La clôture est refusée : les informations envoyées sont invalides (notes finales limitées à 2 000 caractères).";
    case 401:
      return "Votre session a expiré. Reconnectez-vous puis réessayez.";
    case 403:
      return "Accès refusé.";
    case 404:
      return "La préparation ou son exécution n'existe plus : la clôture ne peut pas être créée.";
    case 409:
      return "La clôture est refusée : les conditions (proposition acceptée, dépôt atteint, exécution terminée) ne sont plus remplies, ou une clôture active existe déjà. Rechargez la préparation.";
    case 0:
      return error.message;
    default:
      return error.message;
  }
}

/** Message for a failed soft deletion. */
export function closureDeleteErrorMessage(error: unknown): string {
  if (!(error instanceof ApiError)) {
    return "Une erreur inattendue est survenue. Réessayez.";
  }
  switch (error.status) {
    case 400:
      return "La suppression est refusée : la requête est invalide.";
    case 401:
      return "Votre session a expiré. Reconnectez-vous puis réessayez.";
    case 403:
      return "Accès refusé.";
    case 404:
      return "Cette clôture n'existe plus.";
    case 409:
      return "La suppression a été refusée par le serveur (conflit). Rechargez la clôture.";
    case 0:
      return error.message;
    default:
      return error.message;
  }
}
